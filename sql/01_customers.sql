-- From the user's CUSTOMERS DDL; no owner/tablespace-specific storage options.
-- Constraint names match the development schema, including NEW_TABLE_PK.
CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    customer_name VARCHAR2(200 BYTE) NOT NULL,
    email VARCHAR2(255 BYTE),
    city VARCHAR2(100 BYTE),
    credit NUMBER(12,2) DEFAULT '0',
    status VARCHAR2(20 BYTE) DEFAULT 'ACTIVE' NOT NULL,
    created_date DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT new_table_pk PRIMARY KEY (customer_id),
    CONSTRAINT chk_customers_credit CHECK (credit >= 0),
    CONSTRAINT chk_customers_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'BLOCKED'))
);
